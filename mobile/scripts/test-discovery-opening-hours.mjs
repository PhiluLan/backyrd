import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const compile=file=>ts.transpileModule(fs.readFileSync(new URL(`../${file}`,import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const status={exports:{}};
new Function('exports','require','module',compile('lib/spot-opening-status.ts'))(status.exports,()=>assert.fail('pure status dependency'),status);
const profiles={exports:{}};
new Function('exports','require','module',compile('lib/spot-product-profile.ts'))(profiles.exports,()=>({supabase:{}}),profiles);
const now=new Date(2026,9,20,18,51);
const canonical=(id,regularHours)=>({worldManifestHash:'public-manifest',spot:{spotId:id,source:'WORLD_KNOWLEDGE',regularHours}});
const hours=[{day:'TUESDAY',intervals:[{start:'07:00',end:'18:30'}]}];
const fixtures={kaphi:canonical('kaphi',hours),missing:canonical('missing',[{day:'MONDAY',intervals:[{start:'07:00',end:'23:00'}]}]),unknown:canonical('unknown',null),closed:canonical('closed',[{day:'TUESDAY',intervals:[]}]),legacy:{worldManifestHash:null,spot:{spotId:'legacy',source:'LEGACY_COMPATIBILITY'}},wrong:canonical('other',hours)};
const legacyOpen=[{day_of_week:'Dienstag',open_time:'00:00',close_time:'23:59'}];
let active=0,maxActive=0;const calls=[];
const mod={exports:{}};
new Function('exports','require','module',compile('lib/discovery-opening-hours.ts'))(mod.exports,name=>{
 if(name==='./spot-opening-status')return status.exports;
 if(name==='./spot-product-profile')return {...profiles.exports,getMobileSpotProductProfile:async(id,signal)=>{assert.ok(signal instanceof AbortSignal);calls.push(id);maxActive=Math.max(maxActive,++active);await new Promise(resolve=>setImmediate(resolve));--active;if(id==='failed')throw Error('offline');return fixtures[id]??canonical(id,hours);}};
 if(name==='./requestDeadline')return {withRequestDeadline:task=>task(new AbortController().signal)};
 throw Error(name);
},mod);
const places=['kaphi','missing','unknown','closed','legacy','failed','wrong','kaphi'].map(id=>({id,hours:id==='kaphi'?[]:legacyOpen}));
const result=await mod.exports.loadDiscoveryOpeningStatuses(places,now);
assert.equal(result.kaphi,'closed','Kaphi: known canonical hours override empty old table at 18:51');
assert.equal(result.missing,'unknown','a missing canonical day is unknown, not closed');
assert.equal(result.unknown,'unknown','unknown canonical hours must not inherit conflicting old opening hours');
assert.equal(result.closed,'closed','an explicitly closed day is closed');
assert.equal(result.legacy,'open','explicit legacy-only profiles retain their existing schedule');
assert.equal(result.failed,'unknown','profile failure never promotes legacy hours into certainty');
assert.equal(result.wrong,'unknown','a mismatched place profile must not supply status');
assert.equal(calls.filter(id=>id==='kaphi').length,1,'duplicate cards across rails share one lookup');
assert.ok(maxActive<=4&&maxActive>1,'profile enrichment must be parallel but bounded');
assert.equal(result.kaphi,status.exports.spotOpeningStatusNow(profiles.exports.spotProductOpeningHours(fixtures.kaphi),now,true),'Home and Place Detail resolve the same canonical rows');
assert.deepEqual(await mod.exports.loadDiscoveryOpeningStatuses([],now),{});
console.log('Home hours: Kaphi regression, canonical precedence, explicit closure, missing/unknown day, legacy compatibility, failure isolation and bounded/deduplicated lookups passed.');
